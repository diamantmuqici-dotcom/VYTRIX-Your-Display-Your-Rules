const DICTIONARIES: Record<Language, Partial<Record<TranslationKey, string>>> = { en: EN, fr: FR, de: DE, ru: RU };
const REVERSE: Record<string, TranslationKey> = Object.fromEntries(
  Object.entries(EN).map(([key, value]) => [value, key as TranslationKey]),
);

export function normalizeLanguage(value: string): Language {
  return value === "fr" || value === "de" || value === "ru" ? value : "en";
}

export function translate(language: string, key: TranslationKey): string {
  const lang = normalizeLanguage(language);
  return DICTIONARIES[lang][key] ?? EN[key] ?? key;
}

/** Translates a literal English UI string when it exists in the dictionary. */
export function translateText(language: string, english: string): string {
  const key = REVERSE[english];
  return key ? translate(language, key) : english;
}

export function useT(): (key: TranslationKey) => string {
  const { state } = useApp();
  const language = state.settings.language;
  return (key) => translate(language, key);
}

export function useTranslateText(): (english: string) => string {
  const { state } = useApp();
  const language = state.settings.language;
  return (english) => translateText(language, english);
}
